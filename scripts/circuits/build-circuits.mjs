import {readFile, writeFile, readdir, mkdir} from 'node:fs/promises';
import {resolve} from 'node:path';
import {build} from 'esbuild';

const result = await build({entryPoints: ['src/tracks/CircuitSchema.ts'], bundle: true, platform: 'node', format: 'esm', write: false});
const {validateCircuit} = await import('data:text/javascript;base64,' + Buffer.from(result.outputFiles[0].text).toString('base64'));
const folder = resolve('circuits');
const check = process.argv.includes('--check');
const order = JSON.parse(await readFile('circuits/catalog.json', 'utf8'));
if (new Set(order.map(row => row.id)).size !== order.length || new Set(order.map(row => row.directory)).size !== order.length) {
  throw new Error('Duplicate circuit registration');
}
for (const row of order) {
  if (!/^[a-z0-9-]+$/.test(row.directory)) throw new Error('Invalid circuit directory');
}
const directories = (await readdir(folder, {withFileTypes: true})).filter(entry => entry.isDirectory());
if (directories.length !== order.length || directories.some(entry => !order.some(row => row.directory === entry.name))) {
  throw new Error('Unregistered or missing circuit directory');
}
const importIndex = process.argv.indexOf('--import');
if (importIndex >= 0) {
  if (check || !process.argv[importIndex + 1]) throw new Error('Use --import <CircuitData.json> without --check');
  const data = JSON.parse(await readFile(process.argv[importIndex + 1], 'utf8'));
  validateCircuit(data);
  const entry = order.find(row => row.id === data.id);
  if (!entry) throw new Error('Register the circuit in circuits/catalog.json first');
  await writeFile(resolve(folder, entry.directory, 'circuit.json'), JSON.stringify(data) + '\n');
}
const catalog = [], imports = [], entries = [], loaders = [];
for (const [index, row] of order.entries()) {
  const data = JSON.parse(await readFile(resolve(folder, row.directory, 'circuit.json'), 'utf8'));
  validateCircuit(data);
  if (row.id !== data.id) throw new Error('ID mismatch: ' + row.directory);
  const xs = data.nodes.map(node => node.x), zs = data.nodes.map(node => -node.z);
  const minX = Math.min(...xs), maxX = Math.max(...xs), minZ = Math.min(...zs), maxZ = Math.max(...zs);
  const scale = Math.min(208 / (maxX - minX), 108 / (maxZ - minZ));
  const path = data.nodes.filter((_, j) => j % 3 === 0).map((node, j) =>
    (j ? 'L' : 'M') + (120 + (node.x - (minX + maxX) / 2) * scale).toFixed(1) + ',' + (66 + (-node.z - (minZ + maxZ) / 2) * scale).toFixed(1)
  ).join(' ') + ' Z';
  catalog.push({id: data.id, file: row.directory + '/circuit.json', region: data.display.region, name: data.display.name,
    english: data.name, shortName: data.shortName, length: data.officialLength, turns: data.driving.turns.length, raceLaps: data.raceLaps, path});
  const source = `../../circuits/${row.directory}/circuit.json`;
  loaders.push(` '${data.id}':()=>import('${source}').then(m=>m.default as unknown as CircuitData)`);
  imports.push(`import c${index} from '${source}';`);
  entries.push(` '${data.id}':c${index}`);
}
// The synchronous registry serves Node tests. The application uses the lazy loader.
const registry = `// Generated by npm run tracks:build.\nimport type {CircuitData} from './CircuitData';\n${imports.join('\n')}\nconst circuits={\n${entries.join(',\n')}\n} as unknown as Record<string,CircuitData>;\nexport function circuitData(id:string):CircuitData{const data=circuits[id];if(!data)throw new Error('Unknown circuit: '+id);return data;}\n`;
const loader = `// Generated by npm run tracks:build.\nimport type {CircuitData} from './CircuitData';\nconst loaders:Record<string,()=>Promise<CircuitData>>={\n${loaders.join(',\n')}\n};\nexport function loadCircuit(id:string){const load=loaders[id];if(!load)throw new Error('Unknown circuit: '+id);return load();}\n`;
await mkdir('src/tracks/generated', {recursive: true});
for (const [file, content] of [['src/tracks/CircuitLoader.ts', loader], ['src/tracks/generated/circuit-summaries.json', JSON.stringify(catalog) + '\n'], ['src/tracks/CircuitRegistry.ts', registry]]) {
  if (check) {
    if (await readFile(file, 'utf8') !== content) throw new Error(file + ' is stale; run npm run tracks:build');
  } else await writeFile(file, content);
}
console.log(`${catalog.length} circuits validated; ${check ? 'index current' : 'catalog and registry generated'}.`);
