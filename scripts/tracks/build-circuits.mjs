import {readFile,writeFile,readdir} from 'node:fs/promises';
import {resolve,basename} from 'node:path';
import {build} from 'esbuild';
const result=await build({entryPoints:['src/tracks/CircuitSchema.ts'],bundle:true,platform:'node',format:'esm',write:false});
const {validateCircuit}=await import('data:text/javascript;base64,'+Buffer.from(result.outputFiles[0].text).toString('base64'));
const folder=resolve('src/tracks/circuits'),check=process.argv.includes('--check');
const importIndex=process.argv.indexOf('--import');
if(importIndex>=0){
 if(check||!process.argv[importIndex+1])throw new Error('Use --import <CircuitData.json> without --check');
 const file=resolve(process.argv[importIndex+1]),data=JSON.parse(await readFile(file,'utf8'));validateCircuit(data);
 const catalog=JSON.parse(await readFile('src/tracks/catalog.json','utf8')),entry=catalog.find(c=>c.id===data.id);
 if(!entry)throw new Error('Register a new circuit ID and filename in catalog.json first');
 await writeFile(resolve(folder,entry.file),JSON.stringify(data)+'\n');
}
const order=JSON.parse(await readFile('src/tracks/catalog.json','utf8'));
if(new Set(order.map(c=>c.id)).size!==order.length||new Set(order.map(c=>c.file)).size!==order.length)throw new Error('Duplicate circuit registration');
const files=(await readdir(folder)).filter(f=>f.endsWith('.json'));
if(files.length!==order.length)throw new Error('Unregistered or missing circuit file');
const catalog=[],imports=[],entries=[],loaders=[];
for(const [i,row] of order.entries()){
 if(basename(row.file)!==row.file)throw new Error('Circuit filename must be local');
 const data=JSON.parse(await readFile(resolve(folder,row.file),'utf8'));validateCircuit(data);
 if(row.id!==data.id)throw new Error('ID mismatch: '+row.file);
 const xs=data.nodes.map(n=>n.x),zs=data.nodes.map(n=>-n.z),minX=Math.min(...xs),maxX=Math.max(...xs),minZ=Math.min(...zs),maxZ=Math.max(...zs),scale=Math.min(208/(maxX-minX),108/(maxZ-minZ));
 const path=data.nodes.filter((_,j)=>j%3===0).map((n,j)=>(j?'L':'M')+(120+(n.x-(minX+maxX)/2)*scale).toFixed(1)+','+(66+(-n.z-(minZ+maxZ)/2)*scale).toFixed(1)).join(' ')+' Z';
 catalog.push({id:data.id,file:row.file,region:data.display.region,name:data.display.name,english:data.name,shortName:data.shortName,length:data.officialLength,turns:data.driving.turns.length,raceLaps:data.raceLaps,path});
 loaders.push(` '${data.id}':()=>import('./circuits/${row.file}').then(m=>m.default as unknown as CircuitData)`);
 imports.push(`import c${i} from './circuits/${row.file}';`);entries.push(` '${data.id}':c${i}`);
}
const registry=`// Generated by npm run tracks:build.\nimport type {CircuitData} from './CircuitData';\n${imports.join('\n')}\nconst circuits={\n${entries.join(',\n')}\n} as unknown as Record<string,CircuitData>;\nexport function circuitData(id:string):CircuitData{const data=circuits[id];if(!data)throw new Error('Unknown circuit: '+id);return data;}\n`;
const loader=`// Generated by npm run tracks:build.\nimport type {CircuitData} from './CircuitData';\nconst loaders:Record<string,()=>Promise<CircuitData>>={\n${loaders.join(',\n')}\n};\nexport function loadCircuit(id:string){const load=loaders[id];if(!load)throw new Error('Unknown circuit: '+id);return load();}\n`;
for(const [file,content] of [['src/tracks/CircuitLoader.ts',loader],['src/tracks/catalog.json',JSON.stringify(catalog)+'\n'],['src/tracks/CircuitRegistry.ts',registry]]){
 if(check){if(await readFile(file,'utf8')!==content)throw new Error(file+' is stale; run npm run tracks:build');}
 else await writeFile(file,content);
}
console.log(`${catalog.length} circuits validated; ${check?'index current':'catalog and registry generated'}.`);
